package graph

import (
	"errors"
	"testing"
)

func roleOf(g *Graph, id string) string {
	for _, n := range g.Nodes {
		if n.ID == id {
			s, _ := n.Fields["role"].(string)
			return s
		}
	}
	return "missing"
}

func fn(id, mod, file string, line, end int) Node {
	return Node{ID: id, Kind: KindFunction, Label: id[len("go:x."):], Module: mod, File: file, Line: line, EndLine: end}
}

func TestRolesLibrary(t *testing.T) {
	// no routes, pages, jobs or subscribers: exported functions act as entries
	g := &Graph{
		Nodes: []Node{
			fn("go:x.Parse", "m", "p.go", 1, 30),
			fn("go:x.lex", "m", "p.go", 31, 60),
			fn("go:x.orphan", "m", "p.go", 61, 70),
			fn("go:x.mockThing", "m", "mocks/m.go", 1, 3),
			fn("go:x.gen", "m", "gen.go", 3, 5),
			{ID: "test:go:x.TestParse", Kind: KindTest, Label: "TestParse", Module: "m"},
		},
		Edges: []Edge{
			{From: "go:x.Parse", To: "go:x.lex", Type: Calls},
			{From: "test:go:x.TestParse", To: "go:x.orphan", Type: Calls},
		},
	}
	files := map[string]string{"gen.go": "// Code generated by stringer; DO NOT EDIT.\n\npackage x\n"}
	AssignRoles(g, func(f string) ([]byte, error) {
		if s, ok := files[f]; ok {
			return []byte(s), nil
		}
		return nil, errors.New("no file")
	})
	if g.Nodes[0].Fields["entry_reason"] != "exported" || g.Nodes[0].Entry {
		t.Errorf("Parse: %v entry=%v", g.Nodes[0].Fields, g.Nodes[0].Entry)
	}
	for id, want := range map[string]string{
		"go:x.Parse":          "",
		"go:x.lex":            "",
		"go:x.orphan":         RoleUnreachable,
		"go:x.mockThing":      RoleGenerated,
		"go:x.gen":            RoleGenerated,
		"test:go:x.TestParse": "",
	} {
		if got := roleOf(g, id); got != want {
			t.Errorf("%s: %q, want %q", id, got, want)
		}
	}
}

func TestRolesNoEntries(t *testing.T) {
	// nothing exported and no entries: unreachable is skipped
	g := &Graph{Nodes: []Node{fn("go:x.a", "m", "a.go", 1, 20), fn("go:x.b", "m", "a.go", 21, 40)}}
	AssignRoles(g, nil)
	if r := roleOf(g, "go:x.a"); r != "" {
		t.Errorf("a: %q", r)
	}
}

func TestRolesPassthroughAndEffects(t *testing.T) {
	g := &Graph{
		Nodes: []Node{
			{ID: "route:GET /a", Kind: KindRoute, Label: "/a", Module: "r", Entry: true},
			{ID: "table:t", Kind: KindTable, Label: "t", Module: "db", External: true},
			fn("go:x.handler", "m", "a.go", 1, 3), // called by the route: never a passthrough
			fn("go:x.forward", "m", "a.go", 5, 8),
			fn("go:x.store", "m", "a.go", 10, 30),
			fn("go:x.query", "m", "q.go", 1, 4), // a short leaf whose source runs SQL
		},
		Edges: []Edge{
			{From: "route:GET /a", To: "go:x.handler", Type: Calls},
			{From: "go:x.handler", To: "go:x.forward", Type: Calls},
			{From: "go:x.forward", To: "go:x.store", Type: Calls},
			{From: "go:x.store", To: "table:t", Type: Writes},
			{From: "go:x.store", To: "go:x.query", Type: Calls},
			{From: "go:x.handler", To: "go:x.query", Type: Calls},
			{From: "go:x.forward", To: "go:x.query", Type: Calls},
		},
	}
	AssignRoles(g, func(f string) ([]byte, error) {
		if f == "q.go" {
			return []byte("func query(db *sql.DB) {\n\tdb.QueryRow(`SELECT 1`)\n}\n"), nil
		}
		return []byte("func x() {\n}\n"), nil
	})
	for id, want := range map[string]string{
		"go:x.handler": "",
		"go:x.store":   "",
		"go:x.query":   "", // three callers, but it reads the database
	} {
		if got := roleOf(g, id); got != want {
			t.Errorf("%s: %q, want %q", id, got, want)
		}
	}
	// forward calls two repo functions, so it isn't a passthrough
	if got := roleOf(g, "go:x.forward"); got != "" {
		t.Errorf("forward: %q", got)
	}
	g.Edges = g.Edges[:len(g.Edges)-1]
	for i := range g.Nodes {
		delete(g.Nodes[i].Fields, "role")
	}
	AssignRoles(g, nil)
	if got := roleOf(g, "go:x.forward"); got != RolePassthrough {
		t.Errorf("forward with one callee: %q", got)
	}
}

// TestRolesPackageInit: a package's init functions run when anything in the
// package is part of the program, so what they call is reached; a package
// nothing reaches keeps its init's callees unreachable.
func TestRolesPackageInit(t *testing.T) {
	init1 := fn("go:x.init#1", "a", "a.go", 91, 95)
	init1.Label = "init"
	g := &Graph{
		Nodes: []Node{
			{ID: "route:GET /x", Kind: KindRoute, Label: "GET /x", Module: "a", Entry: true},
			fn("go:x.handle", "a", "a.go", 1, 30),
			fn("go:x.a1", "a", "a.go", 31, 60),
			{ID: "go:x.init", Kind: KindFunction, Label: "init (package vars)", Module: "a", File: "a.go", Line: 61, EndLine: 61},
			fn("go:x.build", "a", "a.go", 62, 90),
			init1,
			fn("go:x.setup", "a", "a.go", 96, 120),
			{ID: "go:y.init", Kind: KindFunction, Label: "init (package vars)", Module: "b", File: "b.go", Line: 1, EndLine: 1},
			fn("go:y.dead", "b", "b.go", 2, 30),
		},
		Edges: []Edge{
			{From: "route:GET /x", To: "go:x.handle", Type: Calls},
			{From: "go:x.handle", To: "go:x.a1", Type: Calls},
			{From: "go:x.init", To: "go:x.build", Type: Calls},
			{From: "go:x.init#1", To: "go:x.setup", Type: Calls},
			{From: "go:y.init", To: "go:y.dead", Type: Calls},
			// effects, so none of them is wiring
			{From: "go:x.build", To: "table:t", Type: Writes},
			{From: "go:x.setup", To: "table:t", Type: Writes},
			{From: "go:y.dead", To: "table:t", Type: Writes},
		},
	}
	g.Nodes = append(g.Nodes, Node{ID: "table:t", Kind: KindTable, Label: "t", External: true})
	AssignRoles(g, nil)
	for id, want := range map[string]string{
		"go:x.init":   RoleWiring,
		"go:x.init#1": RoleWiring,
		"go:y.init":   RoleWiring,
		"go:y.dead":   RoleUnreachable,
	} {
		if got := roleOf(g, id); got != want {
			t.Errorf("%s: role %q, want %q", id, got, want)
		}
	}
	for _, id := range []string{"go:x.build", "go:x.setup"} {
		if got := roleOf(g, id); got == RoleUnreachable {
			t.Errorf("%s is unreachable", id)
		}
	}
}
